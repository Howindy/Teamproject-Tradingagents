@pytest.mark.parametrize("replacement", ["0.0%", "30.0%"])
def test_missing_input_cannot_be_zero_or_invented(replacement):
    text = REPLIES[1]["report"].replace("**n/a**", replacement)
    assert text != REPLIES[1]["report"]
    assert evaluate(1, text)["status"] == "failed"


def test_missing_comparison_cannot_use_qoq():
    text = REPLIES[2]["report"].replace("**n/a — missing_comparison**", "**-1.4%**")
    assert text != REPLIES[2]["report"]
    assert evaluate(2, text)["status"] == "failed"


def test_missing_injection_fails():
    result = evaluate(0, prompts=[{"role": "system", "content": "No program table."}])
    assert not result["checks"]["injection"]


def test_missing_metric_fails():
    text = "\n".join(
        line
        for line in REPLIES[0]["report"].splitlines()
        if not (line.startswith("|") and "current ratio" in line.lower())
    )
    assert evaluate(0, text)["status"] == "failed"


def test_price_cutoff_case_with_independent_expected_na():
    # Synthetic completed S04 checks only gate behavior; never substitutes for
    # the saved real S04 tool-intent reply in the replay evidence.
    reply = REPLIES[3]
    case = DATA["cases"][3]
    system = "\n".join(m["content"] for m in reply["prompts"] if m["role"] == "system")
    table = ["| Metric | Value | Period | Sources |", "|---|---|---|---|"]
    for row in case["expected_rows"]:
        mid = row["metric_id"]
        _, context = gates.metric_rows(system, mid)[0]
        value = (
            row["expected_display"] + " " + row["unit"]
            if row["status"] == "computed"
            else "n/a " + row["reason"]
        )
        table.append(f"| {mid} | {value} | {context} |")
    text = (
        "AAPL fundamental report. The fiscal-year price is not eligible. This synthetic report "
        "retains the disclosed financial metrics and their periods and sources. Missing inputs "
        "are unavailable rather than zero. No future price is accepted and the reported cash "
        "flow span is not a derived single quarter.\n" + "\n".join(table)
    )
    assert gates.score(case, reply["prompts"], text)["status"] == "passed"
    assert (
        gates.score(case, reply["prompts"], text.replace("n/a price_not_completed", "33.4 x"))[
            "status"
        ]
        == "failed"
    )
